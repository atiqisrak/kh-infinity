// Regenerates src/lib/gallery-files.ts from the WebP photos in
// public/images/prod-gallery/:
//
//   Display/iPhone/<brand>/   → iPhone displays
//   Display/android/          → Android (and iPad) displays
//   battery/                  → phone batteries
//   macbook/                  → MacBook parts
//
//   pnpm catalog:gallery
//
// Run it after adding, removing or renaming gallery photos. Resized copies
// such as "-200x200" are skipped (the full-size photo is used instead).
// src/lib/parts-catalog.ts turns the filenames into named catalogue items.

import { readdirSync, writeFileSync } from 'node:fs'
import { join, relative, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const PUBLIC = join(ROOT, 'public')
const GALLERY = join(PUBLIC, 'images', 'prod-gallery')
const OUT = join(ROOT, 'src', 'lib', 'gallery-files.ts')

const SOURCES = {
  iphoneDisplays: 'Display/iPhone',
  androidDisplays: 'Display/android',
  batteries: 'battery',
  macbookParts: 'macbook',
}

// "-200x200", "-800x800", and truncated "-800x8"
const RESIZED_COPY = /-\d+x\d*\.webp$/i

function walk(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((e) =>
    e.isDirectory() ? walk(join(dir, e.name)) : [join(dir, e.name)],
  )
}

let body = `// Generated by scripts/build-display-catalog.mjs — do not edit by hand.
// Run \`pnpm catalog:gallery\` after changing public/images/prod-gallery/.

export const GALLERY_FILES = {
`
for (const [key, sub] of Object.entries(SOURCES)) {
  const all = walk(join(GALLERY, sub)).filter((f) => f.toLowerCase().endsWith('.webp'))
  const files = all
    .filter((f) => !RESIZED_COPY.test(f))
    .map((f) => '/' + relative(PUBLIC, f).split('\\').join('/'))
    .sort((a, b) => a.localeCompare(b, 'en', { numeric: true }))
  body += `  ${key}: [\n${files.map((f) => `    ${JSON.stringify(f)},`).join('\n')}\n  ],\n`
  console.log(`${key}: ${files.length} photos (${all.length - files.length} resized copies skipped)`)
}
body += `} satisfies Record<string, string[]>\n`

writeFileSync(OUT, body)
console.log(`→ ${relative(ROOT, OUT)}`)
