// Regenerates src/lib/iphone-display-files.ts from the WebP photos in
// public/images/prod-gallery/Display/webp/<brand>/.
//
//   pnpm catalog:displays
//
// Run it after adding, removing or renaming display photos. Filenames must
// follow the supplier pattern, e.g.
//   GX-Hard-OLED-Screen-Replacement-For-iPhone-17-Pro-Max.webp
// Extra photos of the same item end in -1, -2 … ; resized copies such as
// "-200x200" are skipped (the full-size photo is used instead).

import { readdirSync, writeFileSync } from 'node:fs'
import { join, relative, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const PUBLIC = join(ROOT, 'public')
const SRC_DIR = join(PUBLIC, 'images', 'prod-gallery', 'Display', 'webp')
const OUT = join(ROOT, 'src', 'lib', 'iphone-display-files.ts')

// "-200x200", "-800x800", and truncated "-800x8"
const RESIZED_COPY = /-\d+x\d*\.webp$/i

function walk(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((e) =>
    e.isDirectory() ? walk(join(dir, e.name)) : [join(dir, e.name)],
  )
}

const all = walk(SRC_DIR).filter((f) => f.toLowerCase().endsWith('.webp'))
const files = all
  .filter((f) => !RESIZED_COPY.test(f))
  .map((f) => '/' + relative(PUBLIC, f).split('\\').join('/'))
  .sort((a, b) => a.localeCompare(b, 'en', { numeric: true }))

const body = `// Generated by scripts/build-display-catalog.mjs — do not edit by hand.
// Run \`pnpm catalog:displays\` after changing public/images/prod-gallery/Display/webp/.

export const DISPLAY_IMAGE_FILES: string[] = [
${files.map((f) => `  '${f}',`).join('\n')}
]
`
writeFileSync(OUT, body)
console.log(`${files.length} photos listed (${all.length - files.length} resized copies skipped) → ${relative(ROOT, OUT)}`)
